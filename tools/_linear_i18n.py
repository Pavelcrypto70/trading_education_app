def _L(
    lang: str,
    title: str,
    sub: str,
    one: str,
    doLive: str,
    doDead: str,
    doSoon: str,
    bad1: str,
    bad2: str,
    lines: list[str],
    hw: list[str],
    outcome: str,
    content: str,
) -> dict:
    """Build one language block. `lines` has 9 strings (0–7 + takeaway); pick is inserted at [8]. `hw` has 3 items."""
    if len(lines) != 9:
        raise ValueError(f"{lang} {title!r}: expected 9 lines, got {len(lines)}")
    if len(hw) != 3:
        raise ValueError(f"{lang} {title!r}: expected 3 hw items, got {len(hw)}")
    full_lines = lines[:8] + [_PICK[lang]] + lines[8:]
    return {
        "title": title,
        "sub": sub,
        "one": one,
        "doLive": doLive,
        "doDead": doDead,
        "doSoon": doSoon,
        "bad1": bad1,
        "bad2": bad2,
        "lines": full_lines,
        "hw": hw + [_HW_SEND[lang]],
        "outcome": outcome,
        "content": content,
    }


