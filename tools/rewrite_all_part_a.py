def translate_meta(lesson: dict, lang: str) -> dict:
    """Return meta fields for a language.

    Full EN/PT body translation is applied elsewhere; for now passthrough RU meta
    (callers may replace title/subtitle/outcome/content/takeaway from a glossary).
    """
    keys = ("title", "subtitle", "outcome", "content", "takeaway")
    return {k: lesson[k] for k in keys if k in lesson}


