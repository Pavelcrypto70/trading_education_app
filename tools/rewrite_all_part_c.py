def S(*parts: dict) -> list[dict]:
    return list(parts)


def h(title: str) -> dict:
    return {"type": "heading", "title": title}


def t(body: str) -> dict:
    return {"type": "text", "body": body}


def c(title: str, chart_type: str, caption: str) -> dict:
    return {"type": "chart", "title": title, "chartType": chart_type, "caption": caption}


def practice(body: str, items: list[str], title: str = "Практика") -> dict:
    return {"type": "practice", "title": title, "body": body, "items": items}


def example(body: str, title: str = "Разбор с цифрами") -> dict:
    return {"type": "example", "title": title, "body": body}


def bullets(items: list[str], title: str = "Запомнить") -> dict:
    return {"type": "bullets", "title": title, "items": items}


