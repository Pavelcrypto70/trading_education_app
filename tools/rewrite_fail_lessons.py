def patch_captions_and_garbage(lesson: dict, lang: str) -> None:
    """Fix useless captions and empty idea templates."""
    caption_fallback = {
        "ru": "Смотрите пример: что отмечено на рисунке = идея блока.",
        "en": "Look at the marked example — it matches this block.",
        "pt": "Veja o exemplo marcado — é a ideia deste bloco.",
    }[lang]
    empty_pat = re.compile(r"примените идею\s*«»|apply the idea\s*['\"]{0,2}|aplique a ideia\s*«»", re.I)
    for s in lesson.get("sections", []):
        if s.get("type") == "chart":
            cap = s.get("caption") or ""
            if "смотрите фигуру, потом текст" in cap.lower() or "look first, then read" in cap.lower() or "veja a figura" in cap.lower() or "Пример по теме этого блока" in cap:
                title = s.get("title") or ""
                s["caption"] = f"{caption_fallback} {title}".strip()
        body = s.get("body")
        if isinstance(body, str) and empty_pat.search(body):
            s["body"] = empty_pat.sub("примените идею этого урока", body)


